// Series catalog: all 42 Tier 1+2 FRED series with metadata and outcome generation config.
// Source of truth: documentation/FRED_MARKETS.md

export type CloudCategory =
  | "inflation"
  | "employment"
  | "consumer"
  | "interestRates"
  | "housing"
  | "production"
  | "gdp"
  | "fedPolicy"
  | "commodities"
  | "credit"
  | "trade";

export type QuestionStyle =
  | "yoyPercent" // YoY % change (CPI, PCE, etc.)
  | "momAbsolute" // MoM absolute change (PAYEMS)
  | "level" // Direct level with brackets (UNRATE, yields)
  | "direction" // Direction vs prior: Cut/Hold/Hike (DFEDTARU)
  | "momPercent" // MoM % change (retail sales, earnings)
  | "qoqAnnualized"; // QoQ annualized % (GDP)

export type DataFrequency =
  | "daily"
  | "weekly"
  | "monthly"
  | "quarterly"
  | "perFomc";

export interface SeriesCatalogEntry {
  seriesId: string;
  name: string;
  category: CloudCategory;
  tier: 1 | 2;
  frequency: DataFrequency;
  source: string;
  questionStyle: QuestionStyle;
  units: string;
  bracketSize: number;
  bracketCount: number; // inner brackets (total outcomes = bracketCount + 2 tails)
  questionTemplate: string;
  copyrighted: boolean;
  closesAtOffsetDays: number;
  resolvesAtOffsetDays: number;
  // Divide raw FRED values by this before display/brackets.
  // E.g. ICSA reports raw 231000 → divisor 1000 → display as 231K
  displayDivisor?: number;
}

